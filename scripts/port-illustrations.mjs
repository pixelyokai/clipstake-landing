// Ports Assets/Illustrations/*.html into scoped markup + CSS for React.
// Classes, keyframes and @property names get a per-file prefix, Geist becomes
// the page font, and animations only run under [data-playing] (removing the
// attribute resets them, so re-adding restarts the loop from the top).
// Usage: node scripts/port-illustrations.mjs
import fs from "node:fs";

const files = [
  ["s1", "Assets/Illustrations/step-1-brief.html"],
  ["s2", "Assets/Illustrations/step-2-submit.html"],
  ["s3", "Assets/Illustrations/step-3-verified-paid.html"],
];

let css = "/* Generated by scripts/port-illustrations.mjs. Do not edit by hand. */\n";
const markup = {};

for (const [prefix, file] of files) {
  const html = fs.readFileSync(file, "utf8");
  let style = html.match(/<style>([\s\S]*?)<\/style>/)[1];
  let body = html.match(/<body>\s*([\s\S]*?)\s*<\/body>/)[1];

  style = style.replace(/body\{margin:0\}\n?/, "");

  const classes = new Set([...style.matchAll(/\.([a-z][a-z0-9-]*)/gi)].map((m) => m[1]));
  const keyframes = new Set([...style.matchAll(/@keyframes ([a-z][a-z0-9-]*)/gi)].map((m) => m[1]));
  const props = new Set([...style.matchAll(/--(n\d)\b/g)].map((m) => m[1]));

  for (const name of keyframes) {
    style = style.replace(new RegExp(`(@keyframes |animation:)${name}\\b`, "g"), `$1${prefix}-${name}`);
  }
  for (const name of props) {
    style = style.replace(new RegExp(`--${name}\\b`, "g"), `--${prefix}-${name}`);
  }
  for (const name of classes) {
    const re = new RegExp(`\\.${name}\\b`, "g");
    style = style.replace(re, `.${prefix}-${name}`);
    body = body.replace(new RegExp(`class="([^"]*\\b)${name}\\b`, "g"), `class="$1${prefix}-${name}`);
  }

  // Animations run only while the frame is playing.
  // Any rule that declares an animation, not just ones that start with it:
  // the view counters set counter-reset first, so they ran forever, even
  // off-screen, recalculating style every frame.
  style = style.replace(
    /(^|\n)(\.[a-z0-9-]+(?:,\.[a-z0-9-]+)*)\{([^{}]*\banimation:[^{}]*)\}/gi,
    (match, lead, selector, body) => {
      const scoped = selector
        .split(",")
        .map((s) => `[data-playing] ${s}`)
        .join(",");
      return `${lead}${scoped}{${body}}`;
    },
  );

  body = body
    .replace(/font-family: 'Geist', system-ui, sans-serif/g, "font-family: var(--font-sans)")
    .replace(/position: relative; width: 720px; height: 640px; overflow: hidden; background: #f9e6e6;/, "position: relative; width: 720px; height: 640px; overflow: hidden;");

  css += `\n/* ${file} */\n${style.trim()}\n`;
  markup[prefix] = body;
}

fs.mkdirSync("src/components/how-it-works", { recursive: true });
fs.writeFileSync("src/components/how-it-works/illustrations.css", css);
fs.writeFileSync(
  "src/components/how-it-works/illustrations.ts",
  "// Generated by scripts/port-illustrations.mjs from Assets/Illustrations. Do not edit by hand.\n" +
    "// Static, trusted markup: rendered with dangerouslySetInnerHTML on the server.\n" +
    Object.entries(markup)
      .map(([k, v]) => `export const ${k.toUpperCase()} = ${JSON.stringify(v)};\n`)
      .join(""),
);
console.log("ported", Object.keys(markup).join(", "));
